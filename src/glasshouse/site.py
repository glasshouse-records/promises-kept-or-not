"""Phase 4 — static evidence site + Atom feed, built straight from the ledger.

Push, not pull: GitHub Pages serves the HTML, the .xml feeds serve
journalists, Datasette serves the SQL (see datasette/metadata.json). No
custom server anywhere. Until publication, `glasshouse site` builds to
data/_site/ for local review (`python -m http.server -d data/_site`).
"""

from __future__ import annotations

import html
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

from .http import DATA_DIR

SITE_DIR = DATA_DIR / "_site"

_CSS = """body{font:16px/1.5 system-ui;margin:2rem auto;max-width:60rem;padding:0 1rem;color:#1a1a1a}
h1,h2{line-height:1.2} table{border-collapse:collapse;width:100%} td,th{border-bottom:1px solid #ddd;
padding:.4rem;text-align:left;vertical-align:top} .q{background:#fff3cd;padding:.2rem .4rem;border-radius:3px}
.meta{color:#666;font-size:.85em} footer{margin-top:3rem;color:#666;font-size:.85em}"""


def _page(title: str, body: str) -> str:
    return (f"<!doctype html><html lang=en><meta charset=utf-8>"
            f"<title>{html.escape(title)} — Glasshouse</title><style>{_CSS}</style>"
            f"<h1>{html.escape(title)}</h1>{body}"
            f"<footer>Generated by Glasshouse. Every claim traces to a primary source; "
            f"resolution types are legally distinct (DPA/NPA ≠ conviction). "
            f"See METHODOLOGY.md. Items marked <span class=q>quarantined</span> are "
            f"unverified leads, not findings.</footer>")


def _e(s) -> str:
    return html.escape(str(s or ""))


def build(conn: sqlite3.Connection, out_dir: Path = SITE_DIR) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    stats = {r[0]: r[1] for r in conn.execute(
        "SELECT 'votes', COUNT(*) FROM votes UNION ALL "
        "SELECT 'enforcement', COUNT(*) FROM enforcement_actions UNION ALL "
        "SELECT 'holdings', COUNT(*) FROM holdings UNION ALL "
        "SELECT 'commitments', COUNT(*) FROM commitments")}

    insts = conn.execute(
        """SELECT i.id, i.display_name,
                  (SELECT COUNT(*) FROM votes v JOIN filings f ON f.accession=v.accession
                   WHERE f.institution_id=i.id) AS n_votes,
                  (SELECT COUNT(*) FROM commitments c WHERE c.institution_id=i.id) AS n_docs
           FROM institutions i ORDER BY n_votes DESC""").fetchall()

    rows = "".join(
        f"<tr><td><a href='institution-{_e(r['id'])}.html'>{_e(r['display_name'])}</a></td>"
        f"<td>{r['n_votes']:,}</td><td>{r['n_docs']}</td></tr>"
        for r in insts)
    body = (f"<p>What financial institutions publicly commit to vs. what they do — "
            f"hold, vote, finance, stay silent about.</p>"
            f"<p class=meta>Ledger: {stats.get('votes',0):,} votes · "
            f"{stats.get('enforcement',0):,} enforcement actions · "
            f"{stats.get('holdings',0):,} holdings · {stats.get('commitments',0):,} "
            f"commitment versions · <a href='candidates.html'>contradiction candidates</a> · "
            f"<a href='feed.xml'>Atom feed</a></p>"
            f"<table><tr><th>Institution</th><th>Votes on record</th><th>Policy versions</th></tr>{rows}</table>")
    (out_dir / "index.html").write_text(_page("Glasshouse", body))

    for r in insts:
        div = conn.execute(
            """SELECT v.issuer_name, v.meeting_date, v.vote_description,
                      COUNT(DISTINCT v.how_voted) AS ways, COUNT(*) AS n
               FROM votes v JOIN filings f ON f.accession=v.accession
               WHERE f.institution_id=? AND v.how_voted != ''
               GROUP BY v.cusip, v.meeting_date, v.vote_description HAVING ways > 1
               ORDER BY n DESC LIMIT 25""", (r["id"],)).fetchall()
        drows = "".join(
            f"<tr><td>{_e(d['issuer_name'])}</td><td>{_e(d['meeting_date'])}</td>"
            f"<td>{_e((d['vote_description'] or '')[:160])}</td><td>{d['ways']}</td></tr>"
            for d in div)
        ibody = (f"<p>{r['n_votes']:,} votes on record; {r['n_docs']} archived policy versions.</p>"
                 f"<h2>Split votes (same proposal, both ways)</h2>"
                 f"<table><tr><th>Issuer</th><th>Meeting</th><th>Proposal</th><th>Ways voted</th></tr>{drows}</table>")
        (out_dir / f"institution-{r['id']}.html").write_text(_page(r["display_name"], ibody))

    from .contradictions import find_commitment_vote_contradictions
    cands = find_commitment_vote_contradictions(conn, limit_per_theme=10)
    crows = "".join(
        f"<tr><td>{_e(c.theme)}</td><td>{_e(c.institution_id)}</td>"
        f"<td>“{_e(c.commitment_quote[:160])}” <span class=meta>({_e(c.doc_label)} @ "
        f"{_e(c.doc_version)})</span></td>"
        f"<td>{_e(c.issuer_name)} {_e(c.meeting_date)}: voted {_e(c.how_voted)} "
        f"({int(c.shares_voted):,} sh) — {_e(c.vote_description[:120])} "
        f"<span class=meta>N-PX {_e(c.accession)}</span></td></tr>"
        for c in cands)
    cbody = (f"<p>ALL rows are <span class=q>quarantined candidates</span>: lexical theme "
             f"matches requiring human review of the commitment and proposal together. "
             f"None is a finding.</p>"
             f"<table><tr><th>Theme</th><th>Institution</th><th>Says</th><th>Did</th></tr>{crows}</table>")
    (out_dir / "candidates.html").write_text(_page("Contradiction candidates", cbody))

    _write_feed(conn, out_dir)
    return {"pages": 2 + len(insts), "candidates": len(cands)}


def _write_feed(conn: sqlite3.Connection, out_dir: Path) -> None:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    entries = []
    for r in conn.execute(
            "SELECT agency, company_name, resolution_type, primary_ref, retrieval_date "
            "FROM enforcement_actions WHERE source_kind='live' ORDER BY id DESC LIMIT 25"):
        title = f"{r['agency']}: {r['company_name']} ({r['resolution_type']})"
        entries.append(
            f"<entry><title>{_e(title)}</title><id>urn:glasshouse:enf:{_e(r['primary_ref'])}"
            f"</id><updated>{_e(r['retrieval_date'])}T00:00:00Z</updated>"
            f"<content type='text'>{_e(r['primary_ref'])}</content></entry>")
    feed = (f"<?xml version='1.0' encoding='utf-8'?>"
            f"<feed xmlns='http://www.w3.org/2005/Atom'>"
            f"<title>Glasshouse — ledger updates</title><id>urn:glasshouse:feed</id>"
            f"<updated>{now}</updated>{''.join(entries)}</feed>")
    (out_dir / "feed.xml").write_text(feed)
